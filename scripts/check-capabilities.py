#!/usr/bin/env python3
"""Validate a CPA plugin capability declaration against the host schema.

Usage:
    check-capabilities.py <path> [<path> ...]

Each path may be a registration JSON file, or a source file / directory to
scan. For source files the script collects declared capability keys and the
pluginabi.Method* constants the dispatch actually references, then reports:

  * capability keys the host does not parse (typos are silently ignored)
  * declared capabilities whose methods are never referenced
  * referenced methods whose capability is not declared
  * executor declared without the required format modifiers

The key list is the authoritative set from internal/pluginhost/rpc_schema.go.
"""
from __future__ import annotations

import json
import os
import re
import sys

# key -> required pluginabi.Method* constant suffixes
CAPABILITIES = {
    "model_registrar": ("ModelRegister",),
    "model_provider": ("ModelStatic", "ModelForAuth"),
    "auth_provider": ("AuthIdentifier", "AuthParse", "AuthLoginStart",
                      "AuthLoginPoll", "AuthRefresh"),
    "frontend_auth_provider": ("FrontendAuthIdentifier", "FrontendAuthAuthenticate"),
    "frontend_auth_provider_exclusive": (),
    "scheduler": ("SchedulerPick",),
    "scheduler_across_priorities": (),
    "model_router": ("ModelRoute",),
    "executor": ("ExecutorIdentifier", "ExecutorExecute", "ExecutorExecuteStream",
                 "ExecutorCountTokens", "ExecutorHTTPRequest"),
    "request_translator": ("RequestTranslate",),
    "request_normalizer": ("RequestNormalize",),
    "request_interceptor": ("RequestInterceptBefore", "RequestInterceptAfter"),
    "request_lifecycle_plugin": ("RequestComplete",),
    "response_translator": ("ResponseTranslate",),
    "response_before_translator": ("ResponseNormalizeBefore",),
    "response_after_translator": ("ResponseNormalizeAfter",),
    "response_interceptor": ("ResponseInterceptAfter",),
    "response_stream_interceptor": ("ResponseInterceptStreamChunk",),
    "websocket_response_observer": ("WebSocketResponseEvent",),
    "thinking_applier": ("ThinkingIdentifier", "ThinkingApply"),
    "usage_plugin": ("UsageHandle",),
    "command_line_plugin": ("CommandLineRegister", "CommandLineExecute"),
    "management_api": ("ManagementRegister", "ManagementHandle"),
    "quota_provider": ("QuotaIdentifier", "QuotaDescribe", "QuotaFetch", "QuotaReset"),
}

EXECUTOR_MODIFIERS = ("executor_model_scope", "executor_input_formats",
                      "executor_output_formats")

VALID_KEYS = set(CAPABILITIES) | set(EXECUTOR_MODIFIERS)
TEXT_SUFFIXES = (".go", ".c", ".rs", ".h", ".py", ".json", ".txt", ".md")
SKIP_DIRS = (".git", "bin", "build", "target", "node_modules")

# Built from chr() rather than an escape sequence: this file is generated by
# heredoc, and backslash escapes do not survive that round trip reliably.
WS = " " + chr(9) + chr(13) + chr(10)

METHOD_RE = re.compile("Method([A-Za-z0-9]+)")


def declared_keys_in(text):
    """Find keys written as a quoted key followed by a colon and true.

    Written as a scan rather than a regex so the script contains no regex
    escape sequences, which are easy to mangle when the file is generated.
    """
    found = set()
    for key in VALID_KEYS:
        needle = '"' + key + '"'
        start = 0
        while True:
            i = text.find(needle, start)
            if i < 0:
                break
            j = i + len(needle)
            while j < len(text) and text[j] in WS:
                j += 1
            if j < len(text) and text[j] == ":":
                j += 1
                while j < len(text) and text[j] in WS:
                    j += 1
                if text.startswith("true", j):
                    found.add(key)
                    break
            start = i + 1
    return found


def declared_any_in(text):
    """Find quoted keys followed by a colon, whatever the value type.

    Modifier fields such as executor_input_formats hold arrays and
    executor_model_scope holds a string, so the boolean-only scan above
    misses them and reports a false 'declared without' error.
    """
    found = set()
    for key in VALID_KEYS:
        needle = chr(34) + key + chr(34)
        start = 0
        while True:
            i = text.find(needle, start)
            if i < 0:
                break
            j = i + len(needle)
            while j < len(text) and text[j] in WS:
                j += 1
            if j < len(text) and text[j] == chr(58):
                found.add(key)
                break
            start = i + 1
    return found


def iter_files(paths):
    out = []
    for p in paths:
        if os.path.isdir(p):
            for root, dirs, files in os.walk(p):
                dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
                for f in files:
                    if os.path.splitext(f)[1] in TEXT_SUFFIXES:
                        out.append(os.path.join(root, f))
        elif os.path.isfile(p):
            out.append(p)
        else:
            print("error: %s does not exist" % p, file=sys.stderr)
            sys.exit(2)
    return out


def find_capabilities(node):
    """Locate a capabilities object anywhere in a decoded registration."""
    if isinstance(node, dict):
        if isinstance(node.get("capabilities"), dict):
            return node["capabilities"]
        for v in node.values():
            hit = find_capabilities(v)
            if hit is not None:
                return hit
    elif isinstance(node, list):
        for v in node:
            hit = find_capabilities(v)
            if hit is not None:
                return hit
    return None


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1

    files = iter_files(argv[1:])
    declared_json = set()
    declared_src = set()
    declared_any = set()
    used = set()

    for path in files:
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError:
            continue
        try:
            caps = find_capabilities(json.loads(text))
        except Exception:
            caps = None
        if caps:
            declared_json.update(k for k, v in caps.items() if v is True)
        declared_src.update(declared_keys_in(text))
        declared_any.update(declared_any_in(text))
        used.update(METHOD_RE.findall(text))

    declared = declared_json or declared_src
    problems = 0

    for key in sorted(declared_json - VALID_KEYS):
        print("ERROR unknown capability key %r: the host ignores it" % key)
        problems += 1

    if not declared:
        print("note: no capability declaration found.")
        print("      pass a registration JSON or a source dir containing one.")
        return 0

    print("declared capabilities:")
    for key in sorted(declared):
        print("  - " + key)
    print()

    for key in sorted(declared):
        for suffix in CAPABILITIES.get(key, ()):
            if suffix not in used:
                print("ERROR %r declared but pluginabi.Method%s is never referenced"
                      % (key, suffix))
                print("      the host will call it and receive unknown_method")
                problems += 1

    if "executor" in declared:
        for mod in EXECUTOR_MODIFIERS[1:]:
            if mod not in declared_any and mod not in declared_json:
                print("ERROR executor declared without %s" % mod)
                print("      executors must declare at least one format")
                problems += 1

    for key, suffixes in sorted(CAPABILITIES.items()):
        if key in declared or not suffixes:
            continue
        if all(s in used for s in suffixes):
            print("warn  %s handled but %r is not declared" % (suffixes[0], key))
            print("      the host will never call it; declare it or drop the handler")
            problems += 1

    print()
    if problems:
        print("%d problem(s) found" % problems)
        return 1
    print("ok: declaration and dispatch are consistent")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
